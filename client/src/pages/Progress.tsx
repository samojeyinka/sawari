import { Link } from 'react-router-dom'
import { useApp } from '../state/store'
import { formatHours, pathPercent } from '../data'
import { Page, PageHeader } from '../components/layout/PageHeader'
import { Button } from '../components/ui/Button'
import { ProgressBar } from '../components/ui/ProgressBar'
import { monoLabel } from '../components/layout/nav'
import { cx } from '../lib/utils'

const dayLabels = () => {
  const names = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat']
  const today = new Date()
  return Array.from({ length: 7 }, (_, i) => {
    const d = new Date(today)
    d.setDate(today.getDate() - (6 - i))
    return names[d.getDay()]
  })
}

interface DynamicMilestone {
  id: string
  title: string
  detail: string
  date: string
  state: 'done' | 'current' | 'next'
  sectionId?: string
  isCapstone?: boolean
}

export function ProgressPage() {
  const { activePath, state } = useApp()

  if (!activePath) {
    return (
      <Page width="narrow">
        <div className="border border-on-band/15 bg-panel px-6 py-16 text-center">
          <p className={monoLabel}>nothing yet</p>
          <h1 className="mt-4 font-display text-[28px] font-light tracking-[-0.025em] text-on-band">
            Nothing to show yet
          </h1>
          <p className="mx-auto mt-3 max-w-sm text-[14.5px] leading-relaxed text-on-band-muted">
            Build a learning path and your sessions, projects and milestones land here.
          </p>
          <Link to="/setup" className="mt-7 inline-block">
            <Button>Build my learning path</Button>
          </Link>
        </div>
      </Page>
    )
  }

  const percent = pathPercent(activePath)
  const stats = activePath.stats
  const currentSection =
    activePath.sections.find((s) => s.id === activePath.currentSectionId) ??
    activePath.sections.find((s) => s.status === 'current') ??
    activePath.sections[0]

  const completedSectionsCount = activePath.sections.filter((s) => s.status === 'completed').length
  const allSectionsDone = completedSectionsCount === activePath.sections.length && activePath.sections.length > 0
  const activeProject = state.projects.find((p) => p.status === 'active')
  const labels = dayLabels()
  const maxWeek = Math.max(...stats.week, 60)

  // Dynamically derive path milestones from the actual sections generated by DeepSeek
  const milestones: DynamicMilestone[] = activePath.sections.map((section) => {
    const isCompleted = section.status === 'completed'
    const isCurrent = section.id === currentSection?.id && !isCompleted
    const progressPercent = section.minutes > 0 ? Math.round((section.doneMinutes / section.minutes) * 100) : 0

    return {
      id: `milestone-${section.id}`,
      sectionId: section.id,
      title: `Section ${section.order}: ${section.title}`,
      detail: section.description || 'Deep domain foundations and applied mastery.',
      date: isCompleted
        ? 'Completed'
        : isCurrent
          ? `${progressPercent}% complete`
          : `${section.minutes} min`,
      state: isCompleted ? 'done' : isCurrent ? 'current' : 'next',
    }
  })

  // Add the path-specific capstone milestone
  milestones.push({
    id: `milestone-capstone-${activePath.id}`,
    title: `Capstone: ${activePath.subject} Mastery`,
    detail: `Apply all concepts learned across the path in a hands-on project to prove domain mastery.`,
    date: allSectionsDone ? 'Ready to build' : 'Final project',
    state: allSectionsDone ? 'current' : 'next',
    isCapstone: true,
  })

  const statsList = [
    { label: 'Path completed', value: `${percent}%` },
    { label: 'Sessions completed', value: String(stats.sessionsCompleted) },
    { label: 'Learning time', value: formatHours(stats.minutesLearned) },
    { label: 'Sections finished', value: `${completedSectionsCount} of ${activePath.sections.length}` },
    { label: 'Topics explored', value: String(stats.topicsExplored || activePath.sections.length) },
  ]

  return (
    <Page width="wide">
      <PageHeader
        eyebrow="Progress"
        title="How far you have come"
        subtitle={`${activePath.subject}, from your foundational sessions to domain mastery.`}
      />

      {/* headline stats */}
      <div className="grid grid-cols-2 gap-x-4 gap-y-6 border-y border-on-band/10 py-6 sm:grid-cols-3 sm:gap-x-6 lg:grid-cols-5">
        {statsList.map((stat, i) => (
          <div key={stat.label} className={cx('animate-rise', `stagger-${Math.min(i + 1, 4)}`)}>
            <p className="font-display text-[28px] font-light leading-none text-on-band">{stat.value}</p>
            <p className={cx(monoLabel, 'mt-2')}>{stat.label}</p>
          </div>
        ))}
      </div>

      <div className="mt-8 grid gap-8 lg:grid-cols-3">
        {/* milestones */}
        <section className="min-w-0 lg:col-span-2">
          <div className="flex items-center justify-between gap-3">
            <h2 className={monoLabel}>Milestones for {activePath.subject}</h2>
            <Link
              to="/app/path"
              className="text-[13px] font-medium text-accent-bright transition-colors hover:text-on-band"
            >
              Open path outline
            </Link>
          </div>

          <ol className="mt-5">
            {milestones.map((milestone) => (
              <li key={milestone.id} className="relative flex gap-4 pb-6 last:pb-0">
                <span className="relative flex shrink-0 justify-center">
                  {milestone.state === 'done' && (
                    <span aria-hidden="true" className="h-7 w-7 shrink-0 bg-success-bright" />
                  )}
                  {milestone.state === 'current' && (
                    <span
                      aria-hidden="true"
                      className="flex h-7 w-7 shrink-0 items-center justify-center border border-accent-bright"
                    >
                      <span className="h-2.5 w-2.5 bg-accent-bright" />
                    </span>
                  )}
                  {milestone.state === 'next' && (
                    <span
                      aria-hidden="true"
                      className="h-7 w-7 shrink-0 border border-dashed border-on-band/20"
                    />
                  )}
                  {milestone.state !== 'next' && (
                    <span aria-hidden="true" className="absolute top-8 h-full w-px bg-on-band/10" />
                  )}
                </span>

                <div className="min-w-0 flex-1 pt-0.5">
                  <div className="flex flex-wrap items-baseline justify-between gap-x-3 gap-y-1">
                    <p
                      className={cx(
                        'text-[15px] font-medium',
                        milestone.state === 'next' ? 'text-on-band-dim' : 'text-on-band',
                      )}
                    >
                      {milestone.title}
                    </p>
                    <span className={monoLabel}>{milestone.date}</span>
                  </div>
                  <p className="mt-1 text-sm leading-relaxed text-on-band-muted">{milestone.detail}</p>

                  {milestone.state === 'current' && milestone.sectionId && (
                    <div className="mt-3">
                      <Link to={`/app/session/${milestone.sectionId}`}>
                        <Button size="sm" variant="secondary">
                          Continue this session
                        </Button>
                      </Link>
                    </div>
                  )}

                  {milestone.state === 'current' && milestone.isCapstone && (
                    <div className="mt-3">
                      <Link to="/app/projects">
                        <Button size="sm" variant="primary">
                          Start Capstone Project
                        </Button>
                      </Link>
                    </div>
                  )}
                </div>
              </li>
            ))}
          </ol>
        </section>

        {/* right column */}
        <aside className="min-w-0 space-y-6">
          <section className="border border-on-band/15 bg-panel p-5">
            <div className="flex items-center justify-between gap-3">
              <h2 className={monoLabel}>This week&apos;s focus</h2>
              <span className={monoLabel}>Target: {activePath.weeklyHours}h/wk</span>
            </div>

            <div className="mt-4 flex h-32 items-end gap-2">
              {stats.week.map((minutes, i) => {
                const height = minutes === 0 ? 3 : Math.max(8, (minutes / maxWeek) * 100)
                return (
                  <div key={i} className="flex min-w-0 flex-1 flex-col items-center gap-2">
                    <div className="flex h-24 w-full items-end">
                      <div
                        className={cx(
                          'w-full transition-all duration-500',
                          minutes === 0 ? 'bg-on-band/10' : 'bg-accent-bright/80',
                        )}
                        style={{ height: `${height}%` }}
                        title={`${minutes} min`}
                      />
                    </div>
                    <span className={monoLabel}>{labels[i]}</span>
                  </div>
                )
              })}
            </div>
            <p className="mt-4 border-t border-on-band/10 pt-3 text-[13px] leading-relaxed text-on-band-dim">
              {stats.week.reduce((a, b) => a + b, 0)} min logged across{' '}
              {stats.week.filter((m) => m > 0).length} active days. Pace is calibrated for{' '}
              {activePath.intensity} learning.
            </p>
          </section>

          <section className="border border-on-band/15 bg-panel p-5">
            <h2 className={monoLabel}>Current focus</h2>

            <div className="mt-3">
              <p className="text-sm font-medium text-on-band">
                {currentSection ? currentSection.title : 'Path complete'}
              </p>
              <p className="mt-1 text-[13px] text-on-band-dim">
                {currentSection
                  ? `Section ${currentSection.order} of ${activePath.sections.length} · ${currentSection.minutes} min`
                  : 'Every section complete. Outstanding work!'}
              </p>

              {currentSection && (
                <div className="mt-3">
                  <ProgressBar
                    value={
                      currentSection.minutes > 0
                        ? (currentSection.doneMinutes / currentSection.minutes) * 100
                        : 0
                    }
                    size="sm"
                  />
                  <Link
                    to={`/app/session/${currentSection.id}`}
                    className="mt-3 inline-block text-[13px] font-medium text-accent-bright transition-colors hover:text-on-band"
                  >
                    Open session
                  </Link>
                </div>
              )}
            </div>

            {activeProject && (
              <div className="mt-4 border-t border-on-band/10 pt-4">
                <p className="text-sm font-medium text-on-band">{activeProject.title}</p>
                <p className="mt-1 text-[13px] text-on-band-dim">
                  {activeProject.completedTaskIds.length} of {activeProject.tasks.length} tasks
                  complete
                </p>
                <Link
                  to={`/app/projects/${activeProject.id}`}
                  className="mt-2 inline-block text-[13px] font-medium text-accent-bright transition-colors hover:text-on-band"
                >
                  Open project workspace
                </Link>
              </div>
            )}
          </section>
        </aside>
      </div>
    </Page>
  )
}
